#!/usr/bin/env node
/**
 * Build the managed Pi MCP extension and its third-party notices.
 *
 * Source:  crates/rovai-core/src/pi/managed-mcp.ts
 * Output:  crates/rovai-core/src/pi/managed-mcp.bundle.mjs      (checked-in build product)
 *          crates/rovai-core/src/pi/managed-mcp.bundle.NOTICES.txt
 *
 * The bundle is a single ESM file with @earendil-works/pi-mcp (MIT) and its
 * dependency closure inlined, so the Pi process never needs a node_modules tree
 * and never resolves anything from a global install. Only Node builtins stay
 * external. `include_str!` in pi.rs embeds the bundle, so this must run before
 * Cargo builds the crate.
 */

import { build } from "esbuild";
import { createHash } from "node:crypto";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, "..");
const source = path.join(root, "crates/rovai-core/src/pi/managed-mcp.ts");
const outfile = path.join(root, "crates/rovai-core/src/pi/managed-mcp.bundle.mjs");
const notices = path.join(root, "crates/rovai-core/src/pi/managed-mcp.bundle.NOTICES.txt");

const REQUIRED_EXPORTS = [
  "createManagedMcpExtension",
  "namespacedToolName",
  "parseFrozenDocument",
  "rejectingRedirectFetch",
  "sanitizeFailure",
  "serverLabel",
  "default"
];

await build({
  entryPoints: [source],
  outfile,
  bundle: true,
  format: "esm",
  platform: "node",
  target: "node22",
  // Node builtins only: no global node_modules, no runtime dependency resolution.
  external: ["node:*"],
  packages: "bundle",
  legalComments: "none",
  // A reproducible bundle keeps the Pi compatibility digest stable.
  //
  // The bundled dependencies (cross-spawn, undici) are CommonJS and call
  // `require("child_process")` and friends. In an ESM output esbuild rewrites those
  // to its `__require` shim, which throws "Dynamic require of ... is not supported"
  // unless a real `require` exists. Defining one from `import.meta.url` resolves
  // every Node builtin through the module system itself, so nothing is resolved
  // from a global or project `node_modules` at runtime.
  banner: {
    js: [
      "// Generated by scripts/build-pi-mcp.mjs. Do not edit; edit managed-mcp.ts.",
      'import { createRequire as __rovaiCreateRequire } from "node:module";',
      "const require = __rovaiCreateRequire(import.meta.url);"
    ].join("\n")
  },
  minify: false,
  sourcemap: false,
  logLevel: "warning"
});

const built = readFileSync(outfile);
const text = built.toString("utf8");
if (text.includes("synthetic-secret")) {
  throw new Error("the bundle must not carry fixture secrets");
}
for (const name of REQUIRED_EXPORTS) {
  if (!text.includes(name)) throw new Error(`the bundle is missing the export ${name}`);
}
if (/\brequire\(\s*["']node_modules/u.test(text)) {
  throw new Error("the bundle must not resolve anything from node_modules at runtime");
}
// Regression guard for the reported failure: without a real `require` the bundled
// CommonJS dependencies throw "Dynamic require of child_process is not supported"
// on the first stdio spawn. The bundle must define one from import.meta.url.
if (!text.includes('from "node:module"') || !text.includes("__rovaiCreateRequire(import.meta.url)")) {
  throw new Error("the bundle must define require via node:module createRequire");
}
if (!text.includes("child_process")) {
  throw new Error("the bundle lost the stdio dependency; cross-spawn should be bundled");
}

const piMcpRoot = path.join(root, "node_modules/@earendil-works/pi-mcp");
const licence = readFileSync(path.join(piMcpRoot, "LICENSES/modelcontextprotocol-typescript-sdk.txt"), "utf8").trim();
const piMcpPackage = JSON.parse(readFileSync(path.join(piMcpRoot, "package.json"), "utf8"));
mkdirSync(path.dirname(notices), { recursive: true });
writeFileSync(
  notices,
  [
    "Third-party notices for managed-mcp.bundle.mjs",
    "",
    `Bundled package: ${piMcpPackage.name}@${piMcpPackage.version} (${piMcpPackage.license})`,
    `Source: ${piMcpPackage.repository?.url ?? "https://github.com/earendil-works/pi"}`,
    "",
    "The MCP client protocol code below is adapted from the MIT-licensed",
    "Model Context Protocol TypeScript SDK v1.29.0. Its licence text follows.",
    "",
    licence,
    ""
  ].join("\n")
);

writeFileSync(
  path.join(root, "crates/rovai-core/src/pi/managed-mcp.bundle.sha256"),
  `sha256:${createHash("sha256").update(built).digest("hex")}\n`
);

process.stdout.write(`built ${path.relative(root, outfile)} (${built.length} bytes)\n`);
